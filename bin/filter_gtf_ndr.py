#! /usr/bin/env python3
from typing import Dict, Set, Tuple
from collections import namedtuple
from GTF import GTF

TranscriptProb = namedtuple("TranscriptProb", ["gene_id", "tx_id", "ndr"])
StrandRecord = namedtuple("StrandRecord", ["ndr", "strand"])

# PARSERS

def parse_bambu(line: list) -> TranscriptProb:
    """
    Parse line of Bambu file.
    Format: TXNAME,GENEID,NDR
    Example: BambuTx1,BambuGene10,0.705533057451248
    """
    tx_id = line[0].lower()
    gene_id = line[1]
    ndr = float(line[2])
    return TranscriptProb(gene_id, tx_id, ndr)


def parse_tfkmers(line: list) -> Tuple[TranscriptProb, str]:
    """
    Parseline of TFKMERS file.
    Format: <gene>::<tx>::<strand>,val1,val2
    Example: BAMBUGENE1::BAMBUTX382::+,0.9773745,0.022625463
    """
    gene_id, tx_id, strand = line[0].split("::")
    ndr = float(line[1])  # third CSV column is NDR
    return TranscriptProb(gene_id, tx_id.lower(), ndr), strand


def parse_ndr(csv, origin: str, th: float) -> Tuple[Set[str], Dict[str, StrandRecord]]:
    s = set()
    strand_dict: Dict[str, StrandRecord] = {}

    # Skip header
    next(csv)

    strand = None
    for line in csv:
        line = line.strip().split(",")

        if origin == "bambu":
            tx_prob = parse_bambu(line)
        elif origin == "tfkmers":
            tx_prob, strand = parse_tfkmers(line)
        else:
            exit("Unknown method")

        if tx_prob.ndr < th:
            s.add(tx_prob.tx_id)

            # Extract strand from sequence name to restrand GTF records
            if origin == "tfkmers":
                # If both extremities are tested, keep only lower extremity prob
                if (
                    tx_prob.tx_id not in strand_dict
                    or tx_prob.ndr < strand_dict[tx_prob.tx_id].ndr
                ):
                    strand_dict[tx_prob.tx_id] = StrandRecord(tx_prob.ndr, strand)

    return s, strand_dict

# FILTER LOGIC

def passes_filter(tx_id: str, args, filter_bambu: Set[str], filter_tfkmers: Set[str]) -> bool:
    """
    Filtering logic based on discovery tool and transcript origin.
    """
    # Keep reference transcripts (not BambuTx or MSTRG)
    if not (tx_id.startswith("mstrg") or tx_id.startswith("bambutx")):
        return True

    # Filtering novel transcripts based on tool and operation
    if args.tx_discovery == "stringtie2":
        return tx_id in filter_tfkmers

    elif args.tx_discovery == "bambu":
        if args.operation == "union":
            return tx_id in filter_bambu or tx_id in filter_tfkmers
        else:
            return tx_id in filter_bambu and tx_id in filter_tfkmers

    elif args.tx_discovery == "both":
        if tx_id.startswith("mstrg"):
            return tx_id in filter_tfkmers
        elif tx_id.startswith("bambutx"):
            if args.operation == "union":
                return tx_id in filter_bambu or tx_id in filter_tfkmers
            else:
                return tx_id in filter_bambu and tx_id in filter_tfkmers
        else:
            return True  # Keep reference transcripts

    else:
        raise ValueError(f"Invalid tx_discovery mode: {args.tx_discovery}")


def filter_count_matrix(file, filter_bambu, filter_tfkmers, args, wr):
    """
    Apply transcript filters to counts matrix.
    """
    header = next(file)
    print(header.strip(), file=wr)

    for line in file:
        tx_id = line.split("\t")[0].lower()
        if passes_filter(tx_id, args, filter_bambu, filter_tfkmers):
            print(line.rstrip(), file=wr)

# MAIN

if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(
        description="Filter your extended GTF generated by ANNEXA. See https://github.com/igdrion/annexa for more informations"
    )

    parser.add_argument(
        "--gtf",
        help="Path to extended_annotations.gtf generated by ANNEXA",
        type=argparse.FileType("r"),
        required=True,
    )
    parser.add_argument(
        "--counts_tx",
        help="Path to counts_transcript.txt",
        type=argparse.FileType("r"),
        required=True,
    )
    parser.add_argument(
        "--bambu",
        help="Path to NDR generated by ANNEXA/bambu",
        type=argparse.FileType("r"),
        required=False,
    )
    parser.add_argument(
        "--bambu-threshold",
        help="Threshold for bambu NDR",
        type=float,
        default=0.2,
    )
    parser.add_argument(
        "--tfkmers",
        help="Path to output.csv generated by ANNEXA/transforkmers",
        type=argparse.FileType("r"),
        required=True,
    )
    parser.add_argument(
        "--tfkmers-threshold",
        help="Threshold for transforkmers NDR",
        type=float,
        default=0.2,
    )
    parser.add_argument(
        "--operation",
        help="Operation for Bambu filtering. Choices: union, intersection",
        type=str,
        default="intersection",
        choices=["union", "intersection"],
    )
    parser.add_argument(
        "--tx_discovery",
        help="Quantification method. Choices: bambu, stringtie2, both",
        type=str,
        choices=["bambu", "stringtie2", "both"],
        required=True,
    )
    args = parser.parse_args()

    ###################################################

    filter_bambu = set()
    if args.tx_discovery in ["bambu", "both"]:
        if not args.bambu:
            raise ValueError("Option --bambu is required for tx_discovery=bambu or both")
        filter_bambu, _ = parse_ndr(args.bambu, "bambu", args.bambu_threshold)

    filter_tfkmers, strand_dict = parse_ndr(
        args.tfkmers, "tfkmers", args.tfkmers_threshold
    )

    with open("unformat.novel.filter.gtf", "w") as wr:
        for record in GTF.parse_by_line(args.gtf):
            if "transcript_id" in record:
                tx_id = record["transcript_id"].lower()
                if passes_filter(tx_id, args, filter_bambu, filter_tfkmers):
                    if tx_id in strand_dict:
                        record.strand = strand_dict[tx_id].strand
                    print(record, file=wr)

    with open("counts_transcript.filter.txt", "w") as wr:
        filter_count_matrix(args.counts_tx, filter_bambu, filter_tfkmers, args, wr)
